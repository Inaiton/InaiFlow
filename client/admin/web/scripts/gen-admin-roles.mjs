// Derives the admin role map from the contract (openapi x-admin-roles) so the UI never hand-codes it.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const spec = JSON.parse(readFileSync(path.resolve(here, "../../../../docs/api/openapi.json"), "utf8"));
const out = {};
for (const [p, ops] of Object.entries(spec.paths)) {
  if (!p.startsWith("/api/v1/admin/")) continue;
  for (const [method, op] of Object.entries(ops)) {
    const roles = op["x-admin-roles"];
    if (!roles) continue;
    out[`${method.toUpperCase()} ${p.replace("/api/v1", "")}`] = roles;
  }
}
const body =
  "// GENERATED by scripts/gen-admin-roles.mjs from docs/api/openapi.json — do not edit.\n" +
  `export const ADMIN_OPERATION_ROLES = ${JSON.stringify(out, null, 2)} as const;\n` +
  "export type AdminOperation = keyof typeof ADMIN_OPERATION_ROLES;\n";
writeFileSync(path.resolve(here, "../src/lib/api/admin-roles.gen.ts"), body);
console.log(`admin-roles.gen.ts: ${Object.keys(out).length} operations`);
